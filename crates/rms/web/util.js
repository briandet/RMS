export function icon(name, cls = 'icon') {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  svg.setAttribute('class', cls);
  const p = document.createElementNS(SVG_NS, 'path');
  p.setAttribute('d', ICONS[name] || ICONS.note);
  svg.append(p);
  return svg;
}

/** Replace <span data-icon="name"> placeholders in static markup. */
export function hydrateIcons(root = document) {
  for (const el of $$('[data-icon]', root)) {
    el.replaceWith(icon(el.dataset.icon, el.className ? `icon ${el.className}` : 'icon'));
  }
}

/** Swap the icon inside a button (keeps other children). */
export function setIcon(btn, name) {
  const old = btn.querySelector('svg');
  const svg = icon(name, old?.getAttribute('class') || 'icon');
  if (old) old.replaceWith(svg); else btn.prepend(svg);
}

// ---------------------------------------------------------------- formatting
export function fmtTime(secs) {
  secs = Math.max(0, Math.floor(+secs || 0));
  const h = Math.floor(secs / 3600), m = Math.floor(secs / 60) % 60, s = secs % 60;
  const ss = String(s).padStart(2, '0');
  return h ? `${h}:${String(m).padStart(2, '0')}:${ss}` : `${m}:${ss}`;
}

export function fmtDuration(secs) {
  secs = Math.round(+secs || 0);
  const h = Math.floor(secs / 3600), m = Math.round((secs % 3600) / 60);
  return h ? `${h} h ${m} min` : `${Math.max(m, secs ? 1 : 0)} min`;
}

export function plural(n, word, pl = word + 's') {
  return `${(+n || 0).toLocaleString()} ${+n === 1 ? word : pl}`;
}

// ---------------------------------------------------------------- misc
export function debounce(fn, ms) {
  let t;
  const d = (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); };
  d.cancel = () => clearTimeout(t);
  return d;
}

/** Leading+trailing throttle. */
export function throttle(fn, ms) {
  let last = 0, t, args;
  return (...a) => {
    args = a;
    const now = Date.now(), wait = ms - (now - last);
    if (wait <= 0) { clearTimeout(t); t = null; last = now; fn(...args); }
    else if (!t) t = setTimeout(() => { t = null; last = Date.now(); fn(...args); }, wait);
  };
}

export const storage = {
  get(key, def = null) {
    try { const v = localStorage.getItem(key); return v == null ? def : v; } catch { return def; }
  },
  set(key, val) {
    try { if (val == null) localStorage.removeItem(key); else localStorage.setItem(key, String(val)); } catch { /* private mode */ }
  },
};

/** Nearest scrollable ancestor (falls back to the document scroller). */
export function scrollParent(el) {
  for (let p = el.parentElement; p; p = p.parentElement) {
    const o = getComputedStyle(p).overflowY;
    if ((o === 'auto' || o === 'scroll') && p.scrollHeight > p.clientHeight) return p;
  }
  return document.scrollingElement || document.documentElement;
}

export function isTyping(target) {
  return !!target?.closest?.('input:not([type=range]):not([type=checkbox]):not([type=radio]), textarea, select, [contenteditable=""], [contenteditable="true"]');
}

// ---------------------------------------------------------------- toasts
let toastRoot;
export function toast(message, type = 'info', ms = type === 'error' ? 6000 : 3000) {
  toastRoot ||= document.getElementById('toasts');
  if (!toastRoot) { console[type === 'error' ? 'error' : 'log'](message); return; }
  // Collapse duplicates that are still on screen.
  for (const t of toastRoot.children) {
    if (t.dataset.msg === message) { t.dataset.count = (+t.dataset.count || 1) + 1; return; }
  }
  const close = () => { el.classList.add('leaving'); setTimeout(() => el.remove(), 200); };
  const el = h('div', { class: `toast toast-${type}`, dataset: { msg: message }, role: type === 'error' ? 'alert' : null },
    h('span', { class: 'toast-msg' }, message),
    h('button', { class: 'icon-btn small', 'aria-label': 'Dismiss notification', onclick: close }, icon('close')));
  toastRoot.append(el);
  while (toastRoot.children.length > 4) toastRoot.firstElementChild.remove();
  setTimeout(close, ms);
}

